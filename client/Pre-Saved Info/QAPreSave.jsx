// ------------------ Is New Freedom faith-based? ------------------

// New Freedom welcomes individuals from all backgrounds, beliefs, and walks of life. While we offer optional recovery church services and spiritual support opportunities, participation in faith-based activities is never required to receive services or participate in the program.


// ------------------ Does New Freedom provide housing? ------------------

// Yes. New Freedom provides structured supportive housing for members participating in residential programming. Housing environments are recovery-focused and designed to promote accountability, stability, safety, and personal growth throughout the re-entry process.


// ------------------ Are meals provided? ------------------

// Yes. Members receive healthy and nutritious meals daily as part of the program. Nutritional wellness plays an important role in supporting physical health, mental wellness, and long-term recovery success.


// ------------------ Is transportation provided upon release? ------------------

// Yes. Assigned peers coordinate transportation directly from correctional facilities upon release whenever possible. Members are welcomed into the program and transported safely to New Freedom’s campus to begin the intake and orientation process.


// ------------------ Do you help members find employment? ------------------

// Yes. Employment readiness and workforce development are core parts of New Freedom’s programming. Members receive support with resume building, interview preparation, job placement assistance, vocational training opportunities, and professional development skills.


// ------------------ Do you help members obtain identification documents? ------------------

// Yes. New Freedom assists members with retrieving or replacing important identification and legal documents necessary for successful reintegration into the community.

// Driver’s License Retrieval
// State Identification Assistance
// Social Security Card Assistance
// Birth Certificate Support
// Legal Documentation Navigation


// ------------------ Are services available after program completion? ------------------

// Yes. New Freedom continues supporting graduates through ongoing outpatient services, peer support, case management, and community navigation resources. These continued services are designed to help graduates maintain stability, recovery, employment, and housing after residential completion.


// ------------------ Are family members allowed to participate in recovery support? ------------------

// Family members and supportive loved ones may participate in approved public meetings, church services, and recovery-related events when appropriate. Healthy support systems are an important part of long-term recovery and successful reintegration.


// ------------------ Does New Freedom provide behavioral health support? ------------------

// Yes. Behavioral health support is integrated throughout New Freedom’s programming through counseling, peer support, wellness services, recovery groups, and coordinated care resources designed to support emotional wellness and long-term recovery.


// ------------------ Does New Freedom offer support for long-term incarceration re-entry? ------------------

// Yes. New Freedom offers specialized support for individuals returning to society after long-term incarceration. Services focus on rebuilding confidence, developing life skills, emotional regulation, community reintegration, and establishing healthy support systems.


// ------------------ Are there opportunities for community involvement? ------------------

// Yes. Community members can support New Freedom through volunteering, donations, mentorship opportunities, public recovery meetings, church services, job fairs, and workforce development partnerships that support second-chance populations.


// ------------------ Does New Freedom work with community partners? ------------------

// Yes. New Freedom collaborates with employers, healthcare providers, behavioral health organizations, community leaders, legal advocates, and workforce development agencies to provide comprehensive support services and long-term opportunities for members.


// ------------------ Can graduates stay connected to New Freedom after completion? ------------------

// Yes. Alumni are encouraged to remain connected through peer support, mentorship opportunities, public events, recovery meetings, church services, and ongoing community engagement activities designed to support long-term success.


// ------------------ Does New Freedom offer peer-led support? ------------------

// Yes. Peer support is one of the foundations of New Freedom’s approach. Many staff members and mentors have lived experience in recovery and re-entry, allowing them to provide guidance through shared understanding, encouragement, and accountability.


// ------------------ What makes New Freedom different? ------------------

// New Freedom combines recovery support, re-entry services, peer mentorship, behavioral health programming, vocational development, and long-term community support into one integrated approach focused on helping individuals rebuild healthy, independent, and purpose-driven lives.